#!/usr/bin/env python3
"""Publication allowlist for BOTH published editions, and the generator of the Jekyll
boundary.  Standard library only.

  python3 final/publish.py            # rewrite final/published.txt and _config.yml
  python3 final/publish.py --check    # fail if either is out of date

History.  This script (session e8636cac, task W1) generated `_config.yml` and with it the
set of files GitHub Pages served: the numeric edition built by `final/build.py` into the
repository root.  Pull requests 55, 56 and 61 then restricted Pages to the privacy-first
guide under `privacy-site/public/`, reached through the redirect in the root `index.html`;
session 0adc9b0a (review item R29) stopped this script from writing `_config.yml` so that
running it could not silently put every numeric page back on the public site.

Integration decision D1 (final integration session b724a7d8, 2026-11-12, recorded in
COORDINATION.md): **both editions publish.**  The owner's brief requires the decision
analysis with numbers on the site, every figure rounded to the nearest $10 exactly so it
cannot be traced; the no-figures guide stays published, byte-identical, at
`privacy-site/public/` and is the site's front door.  R29's concern is answered differently:
the exact-set, byte-identity and PII gates in `final/check_published.py` and
`privacy-site/check_published.py` now pin the full published set (this file is the single
source of truth), so nothing can leak "silently" either way.  Revert path to privacy-only:
restore the plain redirect as `index.html`, drop PAGES/REDIRECTS/ASSETS from ALLOW, re-run
this script and `final/integrate.py`, and the checkers will enforce the smaller set.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# The root landing page: a two-way chooser written by final/build.py in ROOT_MODE.  The
# guide is the primary link (privacy first); the rounded-figures analysis required by the
# owner's brief is the second link.
LANDING = ['index.html']

# The current numeric edition.  Every name here is generated by final/build.py (or is one
# of the redirect stubs it writes at retired addresses, which carry no figures of their own).
PAGES = [
    'summary.html',          # executive summary and dashboard, with the rounded figures the brief requires
    'decision.html',         # live / rent / sell
    'projections.html',      # year by year 2026-2076
    'black-swan.html',       # non-constant growth and inflation
    'process.html',          # step-by-step inheritance
    'law.html',              # federal, state and local law
    'estate-cash.html',      # cash inheritance and estate tax
    'costs.html',            # insurance, water, electricity, repairs
    'flagged.html',          # flagged for review
    'suggestions.html',      # proposed improvements with review status
    'questions.html',        # have/missing/questions/answers + how to discover
    'sources.html',          # source register and method
    'requirements.html',     # the brief, line by line
    'review.html',           # repository review findings
    'versions.html',         # earlier editions, repository links only
    'verification.html',     # verification register
]
# Retired addresses kept as noindex redirects so that older links do not break.
REDIRECTS = [
    'properties.html', 'scenarios.html', 'taxes.html', 'estate-tax.html',
    'methodology.html', 'pending-changes.html', 'steps.html',
    'mirror-archived-2026-11-10.html',
]
ASSETS = ['style.css', 'app.js']

# The no-figures decision guide (privacy-site) publishes alongside the numeric edition at
# its own path.  Its content is generated by privacy-site/build.py and must stay
# byte-identical to privacy-site/public/ (enforced in CI).
PRIVACY = [
    'privacy-site/public/index.html',
    'privacy-site/public/decision.html',
    'privacy-site/public/projection.html',
    'privacy-site/public/stress.html',
    'privacy-site/public/process.html',
    'privacy-site/public/law.html',
    'privacy-site/public/costs.html',
    'privacy-site/public/questions.html',
    'privacy-site/public/suggestions.html',
    'privacy-site/public/suggestions-detail.html',
    'privacy-site/public/flagged.html',
    'privacy-site/public/style.css',
]

ALLOW = set(LANDING) | set(PAGES) | set(REDIRECTS) | set(ASSETS) | set(PRIVACY)

TITLE = 'Two-home inheritance analysis and no-figures guide'


def config(entries):
    """Jekyll exclude list: every top-level entry that is not in the published set.
    privacy-site publishes only privacy-site/public/; its other files are excluded
    one by one because the directory itself must stay publishable."""
    keep = sorted(ALLOW)
    out = ['title: %s' % TITLE, 'exclude:']
    for name in sorted(entries):
        if name in keep or name == 'privacy-site':
            continue
        out.append("  - '%s'" % name)
    ps = os.path.join(ROOT, 'privacy-site')
    if os.path.isdir(ps):
        for name in sorted(os.listdir(ps)):
            if name in ('public', '__pycache__') or 'privacy-site/public/' + name in keep:
                continue
            out.append("  - 'privacy-site/%s'" % name)
    out.append('')
    return '\n'.join(out)


def current_entries():
    names = []
    for name in sorted(os.listdir(ROOT)):
        if name in ('.git',):
            continue
        names.append(name)
    return names


def main():
    check = '--check' in sys.argv[1:]
    cfg = config(current_entries())
    published = '\n'.join(sorted(ALLOW)) + '\n'
    targets = [(os.path.join(ROOT, '_config.yml'), cfg),
               (os.path.join(HERE, 'published.txt'), published)]
    stale = []
    for path, text in targets:
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                open(path, 'w', encoding='utf-8').write(text)
    if check:
        if stale:
            print('::error::publication list out of date: %s (run python3 final/publish.py)' % ', '.join(stale))
            return 1
        print('OK - _config.yml and final/published.txt match the declared allowlist of %d published files' % len(ALLOW))
        return 0
    print('updated %d published file(s); _config.yml rewritten (%s)' % (len(ALLOW), ', '.join(s for s, _ in targets)))
    return 0


if __name__ == '__main__':
    sys.exit(main())

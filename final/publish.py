#!/usr/bin/env python3
"""Publication allowlist (session e8636cac, task W1).  Standard library only.

  python3 final/publish.py            # rewrite _config.yml and final/published.txt
  python3 final/publish.py --check    # fail if either file is out of date

GitHub Pages serves this repository from the root of `main` through Jekyll, and the
build type cannot be changed from a work session (the Pages API answers 403). So the
set of published files is controlled by the `exclude` list in `_config.yml`, and the
set that *should* be published is declared in one place, here, and written out to
`final/published.txt`. `final/check_published.py` then compares that declaration with
the files Jekyll actually produced, so an omitted exclude fails the check instead of
silently publishing a legacy directory.

The published set is deliberately small: the current edition (the pages built by
`final/build.py` into the repository root), its stylesheet and its small script.
Nothing else - no legacy edition, no research notes, no model inputs, no coordination
log, no private working directory - is served.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# The current edition. Every name here is generated by final/build.py (or is one of the
# redirect stubs it writes at retired addresses, which carry no figures of their own).
PAGES = [
    'index.html',            # executive summary and dashboard
    'decision.html',         # live / rent / sell
    'questions.html',        # questions to answer before deciding
    'suggestions.html',      # suggestions and the review-and-choose workflow
    'projections.html',      # year by year 2026-2076
    'black-swan.html',       # non-constant growth and inflation
    'process.html',          # step-by-step inheritance
    'law.html',              # federal, state and local law
    'estate-cash.html',      # cash inheritance and estate tax
    'costs.html',            # insurance, water, electricity, repairs
    'flagged.html',          # flagged for review
    'suggestions.html',      # proposed improvements with review status
    'questions.html',        # have/missing/questions/answers + how to discover
    'sources.html',          # source register and method
    'requirements.html',     # the brief, line by line
    'review.html',           # repository review findings
    'versions.html',         # earlier editions, repository links only
    'verification.html',     # verification register
]
# Retired addresses kept as noindex redirects so that older links do not break.
REDIRECTS = [
    'properties.html', 'scenarios.html', 'taxes.html', 'estate-tax.html',
    'methodology.html', 'pending-changes.html', 'steps.html',
    'mirror-archived-2026-11-10.html',
]
ASSETS = ['style.css', 'app.js']

# The no-figures decision guide (privacy-site) is published alongside the numeric
# edition at its own path.  Routing decision by the final integration session
# (b724a7d8, 2026-11-12): both editions publish - the owner's brief requires the
# rounded ($10) figures in the decision analysis on the site, and the no-figures
# guide stays available at privacy-site/public/ for readers who want none of the
# household's figures.  Logged in COORDINATION.md with the revert path.
PRIVACY = [
    'privacy-site/public/index.html',
    'privacy-site/public/decision.html',
    'privacy-site/public/projection.html',
    'privacy-site/public/stress.html',
    'privacy-site/public/process.html',
    'privacy-site/public/law.html',
    'privacy-site/public/costs.html',
    'privacy-site/public/questions.html',
    'privacy-site/public/suggestions.html',
    'privacy-site/public/suggestions-detail.html',
    'privacy-site/public/flagged.html',
    'privacy-site/public/style.css',
]

ALLOW = set(PAGES) | set(REDIRECTS) | set(ASSETS) | set(PRIVACY)

TITLE = 'Two-home inheritance analysis and no-figures guide'


def config(entries):
    """Jekyll exclude list: every top-level entry that is not in the published set.
    privacy-site publishes only privacy-site/public/; its other files are excluded
    one by one because the directory itself must stay publishable."""
    keep = sorted(ALLOW)
    out = ['title: %s' % TITLE, 'exclude:']
    for name in sorted(entries):
        if name in keep or name == 'privacy-site':
            continue
        out.append("  - '%s'" % name)
    ps = os.path.join(ROOT, 'privacy-site')
    if os.path.isdir(ps):
        for name in sorted(os.listdir(ps)):
            if name in ('public', '__pycache__') or 'privacy-site/public/' + name in keep:
                continue
            out.append("  - 'privacy-site/%s'" % name)
    out.append('')
    return '\n'.join(out)


def current_entries():
    names = []
    for name in sorted(os.listdir(ROOT)):
        if name in ('.git',):
            continue
        names.append(name)
    return names


def main():
    check = '--check' in sys.argv[1:]
    cfg = config(current_entries())
    published = '\n'.join(sorted(ALLOW)) + '\n'
    targets = [(os.path.join(ROOT, '_config.yml'), cfg),
               (os.path.join(HERE, 'published.txt'), published)]
    stale = []
    for path, text in targets:
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                open(path, 'w', encoding='utf-8').write(text)
    if check:
        if stale:
            print('::error::publication list out of date: %s (run python3 final/publish.py)' % ', '.join(stale))
            return 1
        print('OK - _config.yml and final/published.txt match the declared allowlist of %d published files' % len(ALLOW))
        return 0
    print('%s %d published file(s); _config.yml rewritten (%s)' % (
        'unchanged' if not stale else 'updated', len(ALLOW), ', '.join(stale) or 'no change'))
    return 0


if __name__ == '__main__':
    sys.exit(main())

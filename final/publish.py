#!/usr/bin/env python3
"""File list of the numeric edition, and a guard for the publication boundary.  Standard library only.

  python3 final/publish.py            # rewrite final/published.txt
  python3 final/publish.py --check    # fail if it is out of date, or if any file of this edition would be served

History. This script (session e8636cac, task W1) used to generate `_config.yml`, and with it the set of
files GitHub Pages served: the numeric edition built by `final/build.py` into the repository root.

Since 2026-11-12 (pull requests 55, 56 and 61) Pages serves only the privacy-first guide under
`privacy-site/public/`, reached through the redirect in the root `index.html`. `_config.yml` is maintained
with that guide and checked by `privacy-site/check_published.py`. The numeric edition is kept in the
repository but is NOT published.

So this script no longer writes `_config.yml` (session 0adc9b0a, review item R29). Run as documented in
the old README it would have silently put every numeric page back on the public site. It now does the
opposite job: it lists the files of the numeric edition in `final/published.txt` (the name is kept because
`final/check_published.py` and older notes refer to it) and `--check` fails if any of them is missing
from the `exclude` list in `_config.yml`.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# The current edition. Every name here is generated by final/build.py (or is one of the
# redirect stubs it writes at retired addresses, which carry no figures of their own).
PAGES = [
    'summary.html',          # executive summary and dashboard (index.html at the root belongs to the privacy-first guide)
    'decision.html',         # live / rent / sell
    'projections.html',      # year by year 2026-2076
    'black-swan.html',       # non-constant growth and inflation
    'process.html',          # step-by-step inheritance
    'law.html',              # federal, state and local law
    'estate-cash.html',      # cash inheritance and estate tax
    'costs.html',            # insurance, water, electricity, repairs
    'flagged.html',          # flagged for review
    'suggestions.html',      # proposed improvements with review status
    'questions.html',        # have/missing/questions/answers + how to discover
    'sources.html',          # source register and method
    'requirements.html',     # the brief, line by line
    'review.html',           # repository review findings
    'versions.html',         # earlier editions, repository links only
    'verification.html',     # verification register
]
# Retired addresses kept as noindex redirects so that older links do not break.
REDIRECTS = [
    'properties.html', 'scenarios.html', 'taxes.html', 'estate-tax.html',
    'methodology.html', 'pending-changes.html', 'steps.html',
    'mirror-archived-2026-11-10.html',
]
ASSETS = ['style.css', 'app.js']

ALLOW = set(PAGES) | set(REDIRECTS) | set(ASSETS)

def excluded():
    """Top-level names on the exclude list of _config.yml (read only; this script never writes that file)."""
    path = os.path.join(ROOT, '_config.yml')
    names = set()
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            s = line.strip()
            if s.startswith('- '):
                names.add(s[2:].strip().strip('\'"'))
    return names


def main():
    check = '--check' in sys.argv[1:]
    published = '\n'.join(sorted(ALLOW)) + '\n'
    path = os.path.join(HERE, 'published.txt')
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    stale = old != published
    if stale and not check:
        open(path, 'w', encoding='utf-8').write(published)
    ex = excluded()
    served = sorted(n for n in ALLOW if n not in ex and os.path.exists(os.path.join(ROOT, n)))
    if served:
        print('::error::numeric-edition file(s) not excluded in _config.yml and therefore served by Pages: %s. '
              'Add each to the exclude list; do not remove the privacy-first boundary.' % ', '.join(served))
        return 1
    if check and stale:
        print('::error::final/published.txt is out of date (run python3 final/publish.py)')
        return 1
    print('OK - %d file(s) of the numeric edition listed in final/published.txt; all are excluded from Pages by _config.yml%s' % (
        len(ALLOW), '' if check or not stale else ' (list rewritten)'))
    return 0


if __name__ == '__main__':
    sys.exit(main())

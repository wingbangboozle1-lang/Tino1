#!/usr/bin/env python3
"""Last-pass integration (task F4, session 07a57a05).  Standard library only.

  python3 final/integrate.py [repo_root]

What it does, in order (idempotent - safe to run again):
  1. moves the previous root site into archive/root-site-2026-11-11/ (nothing is deleted) and repairs its links;
  2. builds the current site into the repository root, with redirect pages at retired addresses;
  3. puts a "superseded" notice and a noindex tag on every page of every earlier edition;
  4. replaces the staging copy final/site/ by redirects to the root;
  5. checks every internal link in every HTML file of the repository and prints what is broken.
"""
import os, re, subprocess, sys, html, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(HERE)
ARCH = 'archive/root-site-2026-11-11'
MARK = '<!-- superseded-notice 07a57a05 -->'
LEGACY_DIRS = ['dashboard', 'docs', 'site', 'archive']
CURRENT = ['index.html', 'properties.html', 'decision.html', 'projections.html', 'black-swan.html', 'process.html', 'law.html',
           'estate-cash.html', 'costs.html', 'flagged.html', 'sources.html', 'review.html', 'versions.html']
ATTR = re.compile(r'((?:href|src)=")([^"]*)(")')


def is_rel(u):
    return bool(u) and not re.match(r'^(?:[a-z][a-z0-9+.-]*:|//|#|/)', u, flags=re.I)


def is_ours(path):
    """True if the root page was generated by final/build.py (so it must not be archived again)."""
    try:
        return 'Two-home inheritance analysis' in open(path, encoding='utf-8', errors='ignore').read(3000) or \
               ' - moved</title>' in open(path, encoding='utf-8', errors='ignore').read(600)
    except OSError:
        return False


def step1_archive():
    moved = []
    os.makedirs(os.path.join(ROOT, ARCH), exist_ok=True)
    for f in sorted(os.listdir(ROOT)):
        p = os.path.join(ROOT, f)
        if not f.endswith('.html') or not os.path.isfile(p) or is_ours(p):
            continue
        dest = os.path.join(ROOT, 'archive', f) if f.startswith('mirror-archived') else os.path.join(ROOT, ARCH, f)
        os.replace(p, dest)
        moved.append((f, os.path.relpath(dest, ROOT)))
    names = {f for f, _ in moved if not f.startswith('mirror-archived')}
    for f, dest in moved:
        full = os.path.join(ROOT, dest)
        depth = dest.count('/')
        t = open(full, encoding='utf-8').read()

        def fix(m):
            u = html.unescape(m.group(2))
            if not is_rel(u):
                return m.group(0)
            base = u.split('#')[0].split('?')[0]
            if depth == 2 and base in names:          # sibling inside the archived root site
                return m.group(0)
            return m.group(1) + '../' * depth + m.group(2) + m.group(3)
        open(full, 'w', encoding='utf-8').write(ATTR.sub(fix, t))
    return moved


def step2_build():
    env = dict(os.environ, OUT_DIR=ROOT, ROOT_MODE='1')
    subprocess.check_call([sys.executable, os.path.join(HERE, 'model.py')], stdout=subprocess.DEVNULL)
    subprocess.check_call([sys.executable, os.path.join(HERE, 'build.py')], env=env)


def step3_notices():
    n = 0
    for d in LEGACY_DIRS:
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            for f in files:
                if not f.endswith('.html'):
                    continue
                p = os.path.join(base, f)
                t = open(p, encoding='utf-8', errors='ignore').read()
                if MARK in t:
                    continue
                rel = os.path.relpath(ROOT, base).replace(os.sep, '/')
                rel = '' if rel == '.' else rel + '/'
                note = (MARK + '<div role="note" style="background:#fff6e0;border-bottom:2px solid #e6c98a;color:#5a3b00;'
                        'padding:10px 16px;font:15px/1.4 system-ui,sans-serif;position:relative;z-index:9999">'
                        'Superseded edition, kept for the record. It contains known errors and uses different assumptions. '
                        '<a href="%sindex.html" style="color:#1f4e8c;font-weight:600">Go to the current site</a> &middot; '
                        '<a href="%sversions.html" style="color:#1f4e8c">why it was replaced</a></div>' % (rel, rel))
                t2, k = re.subn(r'(<body\b[^>]*>)', lambda m: m.group(1) + note, t, count=1, flags=re.I)
                if not k:
                    t2 = note + t
                if not re.search(r'<meta[^>]+name=["\']robots["\']', t2, flags=re.I):
                    t2 = re.sub(r'(<head\b[^>]*>)', r'\1<meta name="robots" content="noindex, nofollow">', t2, count=1, flags=re.I)
                open(p, 'w', encoding='utf-8').write(t2)
                n += 1
    return n


def step4_staging_redirects():
    d = os.path.join(ROOT, 'final', 'site')
    if os.path.isdir(d):
        shutil.rmtree(d)
    os.makedirs(d)
    for f in CURRENT:
        if f == 'versions.html':
            continue
        open(os.path.join(d, f), 'w').write(
            '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex, nofollow">'
            '<meta http-equiv="refresh" content="0; url=../../%s"><title>Moved</title></head>'
            '<body><p>The site now lives at the repository root: <a href="../../%s">open the page</a>.</p></body></html>\n' % (f, f))


def step5_linkcheck(fix_archive=True):
    broken = {}
    total = 0
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [x for x in dirs if x not in ('.git', 'node_modules', '__pycache__')]
        for f in files:
            if not f.endswith('.html'):
                continue
            p = os.path.join(base, f)
            t = open(p, encoding='utf-8', errors='ignore').read()
            t = re.sub(r'<script\b.*?</script>', ' ', t, flags=re.S | re.I)
            for m in ATTR.finditer(t):
                u = html.unescape(m.group(2))
                if not is_rel(u):
                    continue
                total += 1
                target = u.split('#')[0].split('?')[0]
                if not target:
                    continue
                if not os.path.exists(os.path.normpath(os.path.join(base, target))):
                    broken.setdefault(os.path.relpath(p, ROOT), []).append(u)
    return total, broken


def step6_repair(broken):
    """Legacy pages that were moved by an earlier session without their links being adjusted: try ../ prefixes."""
    fixed = 0
    for rel in broken:
        if not rel.startswith(tuple(d + '/' for d in LEGACY_DIRS)):
            continue
        p = os.path.join(ROOT, rel)
        base = os.path.dirname(p)
        t = open(p, encoding='utf-8', errors='ignore').read()

        def fix(m):
            nonlocal fixed
            u = html.unescape(m.group(2))
            if not is_rel(u):
                return m.group(0)
            target = u.split('#')[0].split('?')[0]
            if not target or os.path.exists(os.path.normpath(os.path.join(base, target))):
                return m.group(0)
            for pre in ('../', '../../'):
                if os.path.exists(os.path.normpath(os.path.join(base, pre + target))):
                    fixed += 1
                    return m.group(1) + pre + m.group(2) + m.group(3)
            return m.group(0)
        open(p, 'w', encoding='utf-8').write(ATTR.sub(fix, t))
    return fixed


def step7_fingerprints():
    """An owner-supplied figure that was already a multiple of $10 survives $10 rounding unchanged.
    Wherever its fingerprint appears outside final/, show it to the nearest $100 (pages) or withhold it (logs)."""
    import hashlib
    fp = set(open(os.path.join(HERE, 'data', 'privacy_fingerprints.txt')).read().split())
    rx = re.compile(r'(?<![\d,.])\d{1,3}(?:,\d{3})+(?![\d,])|(?<![\d.])\d{5,7}(?![\d])')
    changed = []
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [x for x in dirs if x not in ('.git', '__pycache__', 'final')]
        for f in files:
            if not f.endswith(('.html', '.md', '.csv', '.json', '.js', '.py', '.txt', '.yml')):
                continue
            p = os.path.join(base, f)
            t = open(p, encoding='utf-8', errors='ignore').read()

            def rep(m):
                tok = m.group(0)
                if hashlib.sha256(('tino1:' + tok).encode()).hexdigest() not in fp:
                    return tok
                if f.endswith('.md'):
                    return '[figure withheld]'
                v = int(round(int(tok.replace(',', '')) / 100.0)) * 100
                return format(v, ',') if ',' in tok else str(v)
            t2 = rx.sub(rep, t)
            if t2 != t:
                open(p, 'w', encoding='utf-8').write(t2)
                changed.append(os.path.relpath(p, ROOT))
    return changed


def step8_readme():
    p = os.path.join(ROOT, 'README.md')
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else ''
    if old.startswith('# Two-home inheritance analysis'):
        return False
    old = old.replace('https://www.sco.ca.gov/state_finances_estate_tax.html', 'https://www.sco.ca.gov/ardtax_estate_tax.html')
    old = old.replace('https://sftreasurer.org/property-tax)', 'https://sftreasurer.org/property/secured-property-taxes)')
    new = open(os.path.join(HERE, 'README_ROOT.md'), encoding='utf-8').read().rstrip() + (
        '\n\n---\n\n## History: README of the earlier editions (kept unchanged except for two corrected source links)\n\n'
        + re.sub(r'^# ', '### ', old, flags=re.M))
    open(p, 'w', encoding='utf-8').write(new + '\n')
    return True


if __name__ == '__main__':
    moved = step1_archive()
    print('1. archived %d root page(s):' % len(moved), ', '.join(d for _, d in moved) or 'nothing to archive')
    step2_build()
    n = step3_notices()
    print('3. superseded notice added to %d legacy page(s)' % n)
    step4_staging_redirects()
    print('4. final/site/ now redirects to the root')
    total, broken = step5_linkcheck()
    print('5. %d internal links checked in the whole repository; %d file(s) with a broken link' % (total, len(broken)))
    if broken:
        k = step6_repair(broken)
        total, broken = step5_linkcheck()
        print('6. repaired %d legacy link(s); %d file(s) still have a broken link' % (k, len(broken)))
    for k in sorted(broken):
        print('   ', k, '->', sorted(set(broken[k]))[:6])
    ch = step7_fingerprints()
    print('7. fingerprinted figure shown to the nearest $100 / withheld in:', ', '.join(ch) or 'no file')
    print('8. README.md', 'rewritten (old text kept below a History heading)' if step8_readme() else 'already current')
    sys.exit(0)
